"""Isolated Jube development stack: generate secrets, start, smoke-test, stop (TAX-025).

Never prints secrets, never deletes volumes and never touches other Compose projects.
"""

from __future__ import annotations

import argparse
import json
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".local" / "jube.env"
COMPOSE_FILE = ROOT / "integration" / "jube" / "docker-compose.jube.yml"
SOURCE = ROOT / "external" / "jube"
LOCK = ROOT / "integration" / "upstreams.lock.json"
SECRET_KEYS = [
    "JUBE_POSTGRES_PASSWORD",
    "JUBE_JWT_KEY",
    "JUBE_API_HMAC_KEY",
    "JUBE_PASSWORD_HASHING_KEY",
    "JUBE_ELEMENT_ENCRYPTION_KEY",
    "JUBE_ADMIN_PASSWORD",
]
DEFAULT_ADMIN = ("Administrator", "Administrator")


def locked_commit() -> str:
    return str(json.loads(LOCK.read_text())["jube"]["commit"])


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        raise SystemExit("Missing .local/jube.env; run python3 scripts/jube_dev.py env")
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs}


def ensure_env() -> None:
    """Create secrets once; an existing file is kept so data and logins keep working."""
    commit = locked_commit()
    if ENV_FILE.exists():
        env = read_env()
        missing = [k for k in SECRET_KEYS if not env.get(k)]
        if missing:
            raise SystemExit(f".local/jube.env is missing {missing}; fix it manually")
        if env.get("JUBE_SOURCE_COMMIT") != commit:
            raise SystemExit("JUBE_SOURCE_COMMIT differs from the upstream lock; review first")
        print("Kept existing .local/jube.env (secrets not shown)")
        return
    ENV_FILE.parent.mkdir(exist_ok=True)
    lines = ["# Generated by scripts/jube_dev.py for local synthetic development only."]
    lines += [f"{key}={secrets.token_urlsafe(48)}" for key in SECRET_KEYS[:-1]]
    # Mixed character classes for Jube's password policy; still random and never printed.
    lines.append(f"JUBE_ADMIN_PASSWORD=Vt{secrets.token_urlsafe(24)}9!")
    lines += [f"JUBE_SOURCE_COMMIT={commit}", "JUBE_PORT=55501"]
    ENV_FILE.write_text("\n".join(lines) + "\n")
    ENV_FILE.chmod(0o600)
    print("Generated .local/jube.env with new random secrets (not shown)")


def check_source() -> None:
    if not SOURCE.exists():
        raise SystemExit("Missing external/jube; run python3 scripts/upstreams.py fetch jube")
    head = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=SOURCE, text=True).strip()
    if head != locked_commit():
        raise SystemExit("external/jube is not at the locked commit; review before building")


def compose(*args: str) -> list[str]:
    return ["docker", "compose", "-f", str(COMPOSE_FILE), "--env-file", str(ENV_FILE), *args]


def base_url() -> str:
    return f"http://127.0.0.1:{read_env().get('JUBE_PORT', '55501')}"


def request(
    method: str, path: str, body: dict[str, Any] | None = None, token: str | None = None
) -> tuple[int, Any]:
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base_url() + path, data=data, method=method)
    req.add_header("Content-Type", "application/json")
    if token:
        req.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            raw = response.read()
            status = response.status
    except urllib.error.HTTPError as error:
        raw, status = error.read(), error.code
    try:
        return status, json.loads(raw) if raw else None
    except json.JSONDecodeError:
        return status, None


def wait_ready(deadline_s: int) -> None:
    end = time.monotonic() + deadline_s
    while time.monotonic() < end:
        try:
            status, _ = request("GET", "/swagger/v1/swagger.json")
            if status in (200, 401):
                return
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            pass
        time.sleep(5)
    raise SystemExit(f"Jube did not answer within {deadline_s}s; inspect: docker compose logs jube")


def token_from(body: Any) -> str | None:
    if isinstance(body, dict):
        for key in ("token", "Token", "accessToken"):
            if isinstance(body.get(key), str):
                return body[key]
    return None


def login() -> str:
    """Log in as Administrator, performing the mandatory first-login password change once."""
    password = read_env()["JUBE_ADMIN_PASSWORD"]
    status, body = request(
        "POST",
        "/api/Authentication/ByUserNamePassword",
        {"userName": DEFAULT_ADMIN[0], "password": password},
    )
    if status == 200 and token_from(body):
        return str(token_from(body))
    status, body = request(
        "POST",
        "/api/Authentication/ByUserNamePassword",
        {
            "userName": DEFAULT_ADMIN[0],
            "password": DEFAULT_ADMIN[1],
            "newPassword": password,
            "repeatNewPassword": password,
            "passwordChangeState": True,
        },
    )
    token = token_from(body)
    if status != 200 or not token:
        raise SystemExit(f"Jube login failed with HTTP {status}; response not shown")
    print("Changed the default Administrator password to the generated local secret")
    return token


def smoke() -> dict[str, Any]:
    wait_ready(60)
    result: dict[str, Any] = {
        "base_url": base_url(),
        "source_commit": read_env()["JUBE_SOURCE_COMMIT"],
    }
    status, _ = request(
        "POST",
        "/api/Authentication/ByUserNamePassword",
        {"userName": DEFAULT_ADMIN[0], "password": "wrong-" + secrets.token_hex(4)},
    )
    result["wrong_password_status"] = status
    token = login()
    result["login"] = "ok"
    status, spec = request("GET", "/swagger/v1/swagger.json", token=token)
    if status != 200 or not isinstance(spec, dict):
        raise SystemExit(f"Swagger retrieval failed with HTTP {status}")
    paths = sorted(spec.get("paths", {}))
    result["openapi"] = spec.get("openapi") or spec.get("swagger")
    result["api_title"] = spec.get("info", {}).get("title")
    result["api_version"] = spec.get("info", {}).get("version")
    result["path_count"] = len(paths)
    result["case_paths"] = [p for p in paths if "case" in p.lower()][:40]
    result["model_paths"] = [p for p in paths if "invoke" in p.lower() or "/model" in p.lower()][
        :40
    ]
    protected = next((p for p in paths if p.lower().startswith("/api/case")), None)
    if protected:
        result["unauthenticated_probe"] = protected
        result["unauthenticated_status"] = request("GET", protected)[0]
    return result


def stats() -> list[str]:
    ids = subprocess.check_output(compose("ps", "-q"), cwd=ROOT, text=True).split()
    if not ids:
        return []
    fmt = "{{.Name}} {{.MemUsage}} {{.CPUPerc}}"
    out = subprocess.check_output(["docker", "stats", "--no-stream", "--format", fmt, *ids])
    return out.decode().splitlines()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["env", "up", "smoke", "status", "stop"])
    args = parser.parse_args()
    if args.command == "env":
        ensure_env()
    elif args.command == "up":
        check_source()
        ensure_env()
        subprocess.run(compose("up", "-d", "--build", "--wait"), cwd=ROOT, check=True)
        print(f"Jube running at {base_url()}/ (loopback only)")
    elif args.command == "smoke":
        print(json.dumps(smoke(), indent=2))
        print("\n".join(stats()))
    elif args.command == "status":
        subprocess.run(compose("ps"), cwd=ROOT, check=True)
        print("\n".join(stats()))
    elif args.command == "stop":
        # stop, not down: containers and volumes are preserved.
        subprocess.run(compose("stop"), cwd=ROOT, check=True)


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as error:
        sys.exit(f"Command failed ({error.returncode}); data preserved")
