"""Isolated yente development stack with a synthetic-only dataset (TAX-027).

Never downloads OpenSanctions or other licensed data, never prints secrets, never deletes volumes.
"""

from __future__ import annotations

import argparse
import json
import secrets
import subprocess
import time
import urllib.error
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".local" / "yente.env"
COMPOSE_FILE = ROOT / "integration" / "yente" / "docker-compose.yente.yml"
MANIFEST = ROOT / "integration" / "yente" / "manifest.yml"
DATASET = "vati_synthetic"
PORT = "55800"
ALIAS_QUERY: dict[str, Any] = {"schema": "Company", "properties": {"name": ["SBR Trading"]}}
ALIAS_EXPECTED = "vati-syn-co-border-retail"
AMBIGUOUS_QUERY: dict[str, Any] = {
    "schema": "Company",
    "properties": {"name": ["Synthetic Highland Imports"]},
}
AMBIGUOUS_EXPECTED = {"vati-syn-co-highland-imports", "vati-syn-co-highland-import-services"}
UNRELATED_QUERY: dict[str, Any] = {
    "schema": "Company",
    "properties": {"name": ["Quartz Lantern Fisheries"]},
}


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        raise SystemExit("Missing .local/yente.env; run python3 scripts/yente_dev.py env")
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs if not k.startswith("#")}


def ensure_env() -> None:
    if ENV_FILE.exists():
        print("Kept existing .local/yente.env (secrets not shown)")
        return
    ENV_FILE.parent.mkdir(exist_ok=True)
    ENV_FILE.write_text(
        "# Generated by scripts/yente_dev.py for local synthetic development only.\n"
        f"YENTE_UPDATE_TOKEN={secrets.token_urlsafe(32)}\nYENTE_PORT={PORT}\n"
    )
    ENV_FILE.chmod(0o600)
    print("Generated .local/yente.env (secrets not shown)")


def check_manifest_is_local_only(text: str) -> None:
    """Refuse to start if the manifest could fetch external or licensed datasets."""
    active = [line.split("#", 1)[0] for line in text.splitlines()]
    lowered = "\n".join(active).lower()
    for marker in ("http://", "https://", "entities_url", "auth_token", "delivery_token"):
        if marker in lowered:
            raise SystemExit(f"Manifest contains '{marker}'; only local synthetic data is allowed")
    if "catalogs: []" not in lowered:
        raise SystemExit("Manifest must declare 'catalogs: []'")


def compose(*args: str) -> list[str]:
    return ["docker", "compose", "-f", str(COMPOSE_FILE), "--env-file", str(ENV_FILE), *args]


def run(args: list[str], capture: bool = False) -> str:
    result = subprocess.run(args, cwd=ROOT, text=True, capture_output=capture)
    if result.returncode:
        raise SystemExit(f"Command failed ({result.returncode}); data preserved")
    return result.stdout if capture else ""


def request(method: str, path: str, body: Any = None) -> tuple[int, Any]:
    url = f"http://127.0.0.1:{read_env().get('YENTE_PORT', PORT)}{path}"
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method)
    req.add_header("Content-Type", "application/json")
    try:
        with urllib.request.urlopen(req, timeout=30) as response:
            raw, status = response.read(), response.status
    except urllib.error.HTTPError as error:
        raw, status = error.read(), error.code
    try:
        return status, json.loads(raw) if raw else None
    except json.JSONDecodeError:
        return status, None


def wait_indexed(deadline_s: int) -> dict[str, Any]:
    """Wait until the synthetic dataset is indexed and readable through the catalog."""
    end = time.monotonic() + deadline_s
    while time.monotonic() < end:
        try:
            status, catalog = request("GET", "/catalog")
            if status == 200 and isinstance(catalog, dict):
                for ds in catalog.get("datasets", []):
                    if ds.get("name") == DATASET and ds.get("index_current"):
                        return catalog
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            pass
        time.sleep(5)
    raise SystemExit(
        f"{DATASET} not indexed within {deadline_s}s; inspect: docker compose logs app"
    )


def match(query: dict[str, Any]) -> list[dict[str, Any]]:
    status, data = request("POST", f"/match/{DATASET}", {"queries": {"q": query}})
    if status != 200 or not isinstance(data, dict):
        raise SystemExit(f"Match request failed with HTTP {status}")
    return list(data["responses"]["q"]["results"])


def summarise(results: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            "id": r.get("id"),
            "caption": r.get("caption"),
            "score": round(float(r.get("score", 0)), 3),
            "match": r.get("match"),
            "datasets": r.get("datasets"),
        }
        for r in results
    ]


def smoke() -> dict[str, Any]:
    catalog = wait_indexed(300)
    datasets = catalog.get("datasets", [])
    ours = next(ds for ds in datasets if ds.get("name") == DATASET)
    result: dict[str, Any] = {
        "health_status": request("GET", "/healthz")[0],
        "ready_status": request("GET", "/readyz")[0],
        "catalog_datasets": sorted(ds.get("name") for ds in datasets),
        "dataset_version": ours.get("version"),
        "dataset_entity_count": ours.get("entity_count"),
    }
    alias = summarise(match(ALIAS_QUERY))
    result["alias_query"] = ALIAS_QUERY["properties"]["name"][0]
    result["alias_top"] = alias[:1]
    result["alias_ok"] = bool(alias) and alias[0]["id"] == ALIAS_EXPECTED
    ambiguous = summarise(match(AMBIGUOUS_QUERY))
    returned = {r["id"] for r in ambiguous}
    result["ambiguous_query"] = AMBIGUOUS_QUERY["properties"]["name"][0]
    result["ambiguous_candidates"] = [r for r in ambiguous if r["id"] in AMBIGUOUS_EXPECTED]
    result["ambiguous_ok"] = AMBIGUOUS_EXPECTED <= returned
    unrelated = summarise(match(UNRELATED_QUERY))
    result["unrelated_matches"] = [r for r in unrelated if r["match"]]
    result["unknown_dataset_status"] = request(
        "POST", "/match/opensanctions", {"queries": {"q": ALIAS_QUERY}}
    )[0]
    result["update_without_token_status"] = request("POST", "/updatez")[0]
    return result


def stats() -> list[str]:
    ids = run(compose("ps", "-q"), capture=True).split()
    if not ids:
        return []
    fmt = "{{.Name}} {{.MemUsage}} {{.CPUPerc}}"
    return run(["docker", "stats", "--no-stream", "--format", fmt, *ids], capture=True).splitlines()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["env", "up", "smoke", "status", "stop"])
    args = parser.parse_args()
    if args.command == "env":
        ensure_env()
    elif args.command == "up":
        check_manifest_is_local_only(MANIFEST.read_text())
        ensure_env()
        run(compose("up", "-d", "--wait"))
        print(f"yente running at http://127.0.0.1:{read_env().get('YENTE_PORT', PORT)}/")
    elif args.command == "smoke":
        print(json.dumps(smoke(), indent=2))
        print("\n".join(stats()))
    elif args.command == "status":
        run(compose("ps"))
        print("\n".join(stats()))
    elif args.command == "stop":
        run(compose("stop"))  # containers and volumes are preserved


if __name__ == "__main__":
    main()
