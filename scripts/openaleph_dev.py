"""Isolated OpenAleph development stack: env, start, users, smoke, stop (TAX-026).

Never prints secrets or API keys, never deletes volumes, never touches other Compose projects.
Only synthetic documents are ingested.
"""

from __future__ import annotations

import argparse
import json
import re
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
import uuid
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
ENV_FILE = ROOT / ".local" / "openaleph.env"
COMPOSE_FILE = ROOT / "integration" / "openaleph" / "docker-compose.openaleph.yml"
OPENALEPH_TAG = "5.4.0-rc1"  # matches version in the locked source's pyproject.toml
PORT = "55580"
USERS = {"A": "synthetic-officer-a@vati.invalid", "B": "synthetic-officer-b@vati.invalid"}
COLLECTION_FOREIGN_ID = "tax026_synthetic_restricted_a"
SYNTHETIC_DOC = (
    "SYNTHETIC TEST DOCUMENT - NOT REAL TAXPAYER DATA\n"
    "Invoice SYN-INV-0001 from Synthetic Mountain Wholesale to Synthetic Border Retail.\n"
    "Amount: LSL 15000.00. Marker: vati-tax026-synthetic-marker\n"
)
MARKER = "vati-tax026-synthetic-marker"
DB_URI_KEYS = ("OPENALEPH_DB_URI", "PROCRASTINATE_DB_URI", "FTM_FRAGMENTS_URI")


def read_env() -> dict[str, str]:
    if not ENV_FILE.exists():
        raise SystemExit("Missing .local/openaleph.env; run python3 scripts/openaleph_dev.py env")
    pairs = (line.split("=", 1) for line in ENV_FILE.read_text().splitlines() if "=" in line)
    return {k.strip(): v.strip() for k, v in pairs if not k.startswith("#")}


def set_env(key: str, value: str) -> None:
    """Add a key to the env file without rewriting existing values."""
    if key in read_env():
        return
    with ENV_FILE.open("a") as handle:
        handle.write(f"{key}={value}\n")


def ensure_env() -> None:
    if ENV_FILE.exists():
        env = read_env()
        if env.get("OPENALEPH_TAG") != OPENALEPH_TAG:
            raise SystemExit("OPENALEPH_TAG in .local/openaleph.env differs from the pin; review")
        # The image bakes default OPENALEPH_DB_URI/PROCRASTINATE_DB_URI values that take
        # precedence over ALEPH_DATABASE_URI, so every database URI must be set explicitly.
        for key in DB_URI_KEYS:
            set_env(key, env["ALEPH_DATABASE_URI"])
        print("Kept existing .local/openaleph.env (secrets not shown)")
        return
    password = secrets.token_hex(24)
    db = f"postgresql://aleph:{password}@postgres/aleph"
    lines = [
        "# Generated by scripts/openaleph_dev.py for local synthetic development only.",
        f"OA_POSTGRES_PASSWORD={password}",
        f"ALEPH_SECRET_KEY={secrets.token_hex(32)}",
        f"ALEPH_DATABASE_URI={db}",
        *(f"{key}={db}" for key in DB_URI_KEYS),
        "ALEPH_ELASTICSEARCH_URI=http://elasticsearch:9200",
        "REDIS_URL=redis://redis:6379/0",
        "ARCHIVE_TYPE=file",
        "ARCHIVE_PATH=/data",
        "ALEPH_SINGLE_USER=false",
        "ALEPH_PASSWORD_LOGIN=true",
        "ALEPH_OAUTH=false",
        f"ALEPH_UI_URL=http://127.0.0.1:{PORT}/",
        "ALEPH_APP_TITLE=OpenAleph (Vati synthetic dev)",
        "ALEPH_OCR_DEFAULTS=eng",
        "ALEPH_DEBUG=false",
        "LOG_FORMAT=TEXT",
        f"OPENALEPH_TAG={OPENALEPH_TAG}",
        f"OPENALEPH_PORT={PORT}",
    ]
    ENV_FILE.parent.mkdir(exist_ok=True)
    ENV_FILE.write_text("\n".join(lines) + "\n")
    ENV_FILE.chmod(0o600)
    print("Generated .local/openaleph.env with new random secrets (not shown)")


def compose(*args: str) -> list[str]:
    return ["docker", "compose", "-f", str(COMPOSE_FILE), "--env-file", str(ENV_FILE), *args]


def run(args: list[str], capture: bool = False) -> str:
    result = subprocess.run(args, cwd=ROOT, text=True, capture_output=capture)
    if result.returncode:
        raise SystemExit(f"Command failed ({result.returncode}); data preserved")
    return result.stdout if capture else ""


def base_url() -> str:
    return f"http://127.0.0.1:{read_env().get('OPENALEPH_PORT', PORT)}"


def request(
    method: str,
    path: str,
    key: str | None = None,
    body: bytes | None = None,
    content_type: str = "application/json",
) -> tuple[int, Any]:
    req = urllib.request.Request(base_url() + path, data=body, method=method)
    if body is not None:
        req.add_header("Content-Type", content_type)
    if key:
        req.add_header("Authorization", f"ApiKey {key}")
    try:
        with urllib.request.urlopen(req, timeout=60) as response:
            raw, status = response.read(), response.status
    except urllib.error.HTTPError as error:
        raw, status = error.read(), error.code
    try:
        return status, json.loads(raw) if raw else None
    except json.JSONDecodeError:
        return status, None


def wait_http(path: str, deadline_s: int) -> None:
    end = time.monotonic() + deadline_s
    while time.monotonic() < end:
        try:
            status, _ = request("GET", path)
            if status == 200:
                return
        except (urllib.error.URLError, ConnectionError, TimeoutError):
            pass
        time.sleep(5)
    raise SystemExit(f"{path} not ready within {deadline_s}s; inspect: docker compose logs api ui")


def up() -> None:
    ensure_env()
    run(compose("pull", "--quiet"))
    run(compose("up", "-d", "--wait", "postgres", "redis", "elasticsearch"))
    # Same initialisation step as upstream contrib/start-local.sh.
    run(compose("run", "--rm", "worker", "aleph", "upgrade"))
    run(compose("up", "-d"))
    wait_http("/api/2/metadata", 300)
    print(f"OpenAleph running at {base_url()}/ (loopback only)")


def ensure_users() -> None:
    """Create two synthetic non-admin users once; API keys go only to the ignored env file."""
    for label, email in USERS.items():
        key_name = f"OA_USER_{label}_API_KEY"
        if read_env().get(key_name):
            continue
        out = run(
            compose(
                "exec",
                "-T",
                "api",
                "aleph",
                "createuser",
                email,
                "--name",
                f"Synthetic officer {label}",
                "--password",
                secrets.token_urlsafe(24),
            ),
            capture=True,
        )
        match = re.search(r"API Key: (\S+)", out)
        if not match or match.group(1) == "None":
            raise SystemExit(f"Could not obtain an API key for synthetic user {label}")
        set_env(key_name, match.group(1))
        print(f"Created synthetic user {label} (API key stored in .local/openaleph.env)")


def ensure_collection(key: str) -> int:
    env = read_env()
    if env.get("OA_COLLECTION_A_ID"):
        return int(env["OA_COLLECTION_A_ID"])
    body = {
        "label": "TAX-026 synthetic restricted collection",
        "foreign_id": COLLECTION_FOREIGN_ID,
        "category": "other",
        "summary": "Synthetic test data only. Not real taxpayer information.",
    }
    status, data = request("POST", "/api/2/collections", key, json.dumps(body).encode())
    if status != 200 or not isinstance(data, dict) or "id" not in data:
        raise SystemExit(f"Collection creation failed with HTTP {status}")
    set_env("OA_COLLECTION_A_ID", str(data["id"]))
    return int(data["id"])


def ingest(key: str, collection_id: int) -> int:
    boundary = uuid.uuid4().hex
    meta = json.dumps({"file_name": "synthetic-invoice-tax026.txt", "languages": ["en"]})
    parts = [
        f'--{boundary}\r\nContent-Disposition: form-data; name="meta"\r\n\r\n{meta}\r\n',
        f'--{boundary}\r\nContent-Disposition: form-data; name="file"; '
        f'filename="synthetic-invoice-tax026.txt"\r\nContent-Type: text/plain\r\n\r\n'
        f"{SYNTHETIC_DOC}\r\n",
        f"--{boundary}--\r\n",
    ]
    status, _ = request(
        "POST",
        f"/api/2/collections/{collection_id}/ingest",
        key,
        "".join(parts).encode(),
        f"multipart/form-data; boundary={boundary}",
    )
    return status


def search(key: str | None, collection_id: int) -> tuple[int, list[dict[str, Any]]]:
    query = urllib.parse.urlencode({"q": MARKER, "filter:collection_id": collection_id})
    status, data = request("GET", f"/api/2/search?{query}", key)
    results = data.get("results", []) if isinstance(data, dict) else []
    return status, results


def smoke() -> dict[str, Any]:
    wait_http("/api/2/metadata", 120)
    ensure_users()
    env = read_env()
    key_a, key_b = env["OA_USER_A_API_KEY"], env["OA_USER_B_API_KEY"]
    result: dict[str, Any] = {"base_url": base_url(), "openaleph_tag": OPENALEPH_TAG}
    status, meta = request("GET", "/api/2/metadata")
    result["metadata_status"] = status
    if isinstance(meta, dict):
        result["app"] = {k: meta.get("app", {}).get(k) for k in ("title", "version")}
    result["anonymous_create_collection_status"] = request(
        "POST", "/api/2/collections", None, json.dumps({"label": "anon"}).encode()
    )[0]
    collection_id = ensure_collection(key_a)
    result["collection_id"] = collection_id
    result["invalid_key_collection_status"] = request(
        "GET", f"/api/2/collections/{collection_id}", "invalid-" + secrets.token_hex(8)
    )[0]
    found: list[dict[str, Any]] = []
    status, found = search(key_a, collection_id)
    if not found:
        result["ingest_status"] = ingest(key_a, collection_id)
        deadline = time.monotonic() + 600
        while not found and time.monotonic() < deadline:
            time.sleep(10)
            status, found = search(key_a, collection_id)
        result["indexed_after_s"] = round(600 - (deadline - time.monotonic()))
    if not found:
        raise SystemExit("Synthetic document was not searchable within 10 minutes")
    entity_id = found[0]["id"]
    status, entity = request("GET", f"/api/2/entities/{entity_id}", key_a)
    props = entity.get("properties", {}) if isinstance(entity, dict) else {}
    result["owner_retrieve_status"] = status
    result["owner_entity_schema"] = entity.get("schema") if isinstance(entity, dict) else None
    result["owner_content_hash_present"] = bool(props.get("contentHash"))
    result["owner_marker_in_text"] = MARKER in json.dumps(props)
    result["other_user_collection_status"] = request(
        "GET", f"/api/2/collections/{collection_id}", key_b
    )[0]
    result["other_user_entity_status"] = request("GET", f"/api/2/entities/{entity_id}", key_b)[0]
    result["other_user_search_hits"] = len(search(key_b, collection_id)[1])
    result["anonymous_collection_status"] = request("GET", f"/api/2/collections/{collection_id}")[0]
    result["anonymous_search_hits"] = len(search(None, collection_id)[1])
    return result


def stats() -> list[str]:
    ids = run(compose("ps", "-q"), capture=True).split()
    if not ids:
        return []
    fmt = "{{.Name}} {{.MemUsage}} {{.CPUPerc}}"
    return run(["docker", "stats", "--no-stream", "--format", fmt, *ids], capture=True).splitlines()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=["env", "up", "smoke", "status", "stop"])
    args = parser.parse_args()
    if args.command == "env":
        ensure_env()
    elif args.command == "up":
        up()
    elif args.command == "smoke":
        print(json.dumps(smoke(), indent=2))
        print("\n".join(stats()))
    elif args.command == "status":
        run(compose("ps"))
        print("\n".join(stats()))
    elif args.command == "stop":
        run(compose("stop"))  # containers and volumes are preserved


if __name__ == "__main__":
    try:
        main()
    except KeyboardInterrupt:
        sys.exit(130)
