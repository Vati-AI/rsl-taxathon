"""Taxpayer portal page guard.

``taxpayer.html`` next to this file is generated by ``npm run build -w
@vati/taxpayer-web`` and is not committed. ``hooks.website_route_rules`` maps
every ``/taxpayer/...`` path here so the Vue router can own client routes.
Mirrors Frappe v16 ``frappe/www/desk.py``: guests are redirected to login.
"""

import frappe
import frappe.sessions

from vati_tax.portal.access import portal_access

no_cache = 1


def get_context(context):
    decision = portal_access(frappe.session.user, frappe.request.path)
    if decision.outcome == "login":
        frappe.redirect(decision.location)

    csrf_token = frappe.sessions.get_csrf_token()
    # get_csrf_token stores the token on the session; persist it before render.
    frappe.db.commit()
    context.no_cache = 1
    context.boot = {"csrf_token": csrf_token}
    return context
