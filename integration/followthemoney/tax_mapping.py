def bundle_from_tax024(record: Mapping[str, Any], tenant_id: str) -> dict[str, Any]:
    """Build a bundle from one synthetic TAX-024 scenario record (no ownership or files).

    Counterparties are ``legal_entity`` because the fixture does not say whether they are
    companies. Amounts are in LSL, as the fixture notes state.
    """
    if record.get("synthetic") is not True:
        raise _fail("Only synthetic records may be mapped here", "synthetic", "not_synthetic")

    def src(record_type: str, record_id: str) -> dict[str, str]:
        return {"system": "synthetic_fixture", "record_type": record_type, "record_id": record_id}

    taxpayer = record["taxpayer_id"]
    counterparties = sorted(
        {c["counterparty_id"] for c in record["contracts"]}
        | {i["counterparty_id"] for i in record["invoices"]}
    )
    parties = [
        {
            "id": taxpayer,
            "kind": "company",
            "name": f"Synthetic taxpayer {taxpayer}",
            "role": "taxpayer",
            "country": "ls",
            "source": src("taxpayer", taxpayer),
        }
    ] + [
        {
            "id": cp,
            "kind": "legal_entity",
            "name": f"Synthetic counterparty {cp}",
            "role": "counterparty",
            "source": src("counterparty", cp),
        }
        for cp in counterparties
    ]
    contracts = [
        {
            "id": c["id"],
            "title": c["description"],
            "buyer_id": taxpayer,
            "supplier_id": c["counterparty_id"],
            "related_party": c["related_party"],
            "source": src("contract", c["id"]),
        }
        for c in record["contracts"]
    ]
    invoices = []
    parties_of: dict[str, tuple[str, str]] = {}  # invoice id -> (buyer, supplier)
    for inv in record["invoices"]:
        if inv["direction"] == "purchase":
            supplier, buyer = inv["counterparty_id"], taxpayer
        else:
            supplier, buyer = taxpayer, inv["counterparty_id"]
        parties_of[inv["id"]] = (buyer, supplier)
        invoices.append(
            {
                "id": inv["id"],
                "direction": inv["direction"],
                "supplier_id": supplier,
                "buyer_id": buyer,
                "contract_id": inv.get("contract_id"),
                "currency": "LSL",
                "net_amount": inv["net_amount"],
                "vat_amount": inv["vat_amount"],
                "gross_amount": inv["gross_amount"],
                "source": src("invoice", inv["id"]),
            }
        )
    payments = [
        {
            "id": p["id"],
            "invoice_id": p["invoice_id"],
            "payer_id": parties_of[p["invoice_id"]][0],
            "beneficiary_id": parties_of[p["invoice_id"]][1],
            "amount": p["amount"],
            "currency": "LSL",
            "source": src("payment", p["id"]),
        }
        for p in record["payments"]
    ]
    return {
        "version": BUNDLE_VERSION,
        "tenant_id": tenant_id,
        "parties": parties,
        "contracts": contracts,
        "invoices": invoices,
        "payments": payments,
        "ownership": [],
        "evidence": [],
    }
