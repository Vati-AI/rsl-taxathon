"""Map Vati tax records to FollowTheMoney entities plus a documented tax extension (TAX-036).

Input is a ``tax_entity_bundle.v1`` (see integration/followthemoney/README.md): parties,
ownership, contracts, invoices, payments and the evidence they cite. Output is

- ``entities``: FtM entity dicts (``id``, ``schema``, ``properties``) using only schemata
  and properties present in the locked FtM source, as recorded in
  ``ftm_schema_subset.v1.json`` (generated by ``scripts/ftm_schema_subset.py``);
- ``extensions``: one ``vati_tax_extension.v1`` record per entity holding what FtM has no
  property for (typed tax amounts, invoice direction, related-party flag, the source record
  and the TAX-032 ``EvidenceRef`` citations with their SHA-256);
- ``conflicts``: ownership records that disagree. Both sides are mapped and both are
  flagged. Nothing is resolved, merged or dropped here.

FtM has no invoice schema. An invoice is an ``UnknownLink`` (supplier -> buyer, role
``Purchase invoice`` or ``Sales invoice``) and its amounts live in the extension. The
evidence SHA-256 is not written to ``Document.contentHash``: that property is FtM's
``checksum`` type, which OpenAleph strips from non-admin bulk writes
(``remove_checksums`` in aleph/logic/processing.py) and which Aleph uses for its own
archive hash. It stays in the extension's ``evidence`` citations.

Entity IDs are deterministic per tenant (``vt-`` + SHA-256 of tenant, kind and record ID),
so mapping the same bundle twice gives identical entities and digests. OpenAleph signs IDs
per collection on write (``collection.ns.apply``). The module needs only the standard
library so ``scripts/dev.py check`` can run its tests with any interpreter.
"""

from __future__ import annotations

import hashlib
import json
import re
import uuid
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from datetime import date
from decimal import Decimal, InvalidOperation
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
SUBSET_PATH = ROOT / "integration" / "followthemoney" / "ftm_schema_subset.v1.json"
BUNDLE_VERSION = "tax_entity_bundle.v1"
EXTENSION_VERSION = "vati_tax_extension.v1"

PARTY_SCHEMA = {"company": "Company", "person": "Person", "legal_entity": "LegalEntity"}
PARTY_ROLES = {"taxpayer", "counterparty", "owner"}
SOURCE_SYSTEMS = {"frappe", "synthetic_fixture"}
INVOICE_ROLE = {"purchase": "Purchase invoice", "sale": "Sales invoice"}
OWNERSHIP_TYPES = {"beneficial", "direct", "indirect", "ultimate"}
# Contract RegisterDocumentRequest media types (integration/api/openapi.json, ADR-011).
MEDIA_TYPES = {
    "application/pdf",
    "image/png",
    "image/jpeg",
    "text/csv",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
}
MAX_EVIDENCE_BYTES = 26_214_400
SHA256 = re.compile(r"[0-9a-f]{64}")
MONEY = re.compile(r"-?\d{1,15}\.\d{2}")
PERCENT = re.compile(r"\d{1,3}(\.\d{1,4})?")
CURRENCY = re.compile(r"[A-Z]{3}")
COUNTRY = re.compile(r"[a-z]{2}")
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
FTM_DATE = re.compile(r"\d{4}(-\d{2}(-\d{2})?)?")
FTM_NUMBER = re.compile(r"-?\d+(\.\d+)?")
RECORD_ID = re.compile(r"[A-Za-z0-9][A-Za-z0-9._:/-]{0,127}")
HUNDRED = Decimal("100")
OPEN_START, OPEN_END = "0000-01-01", "9999-12-31"


class MappingError(ValueError):
    """The bundle cannot be mapped. ``code`` is the ADR-003 ``invalid_domain_input``;
    ``field`` points at the offending input and ``reason`` is machine-readable."""

    def __init__(self, message: str, *, field: str, reason: str) -> None:
        super().__init__(message)
        self.code = "invalid_domain_input"
        self.field = field
        self.reason = reason


class EntityValidationError(ValueError):
    """An emitted entity does not conform to the locked FtM schema subset."""


@dataclass
class MappingResult:
    entities: list[dict[str, Any]]
    extensions: list[dict[str, Any]]
    conflicts: list[dict[str, Any]]
    digests: dict[str, str] = field(default_factory=dict)

    def entity(self, entity_id: str) -> dict[str, Any]:
        return next(e for e in self.entities if e["id"] == entity_id)

    def extension(self, entity_id: str) -> dict[str, Any]:
        return next(x for x in self.extensions if x["entity_id"] == entity_id)


def load_subset(path: Path = SUBSET_PATH) -> dict[str, Any]:
    data = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(data.get("schemata"), dict) or not data.get("source", {}).get("commit"):
        raise EntityValidationError("FtM schema subset is missing its schemata or source commit")
    return data


SUBSET = load_subset()


def entity_id(tenant_id: str, kind: str, record_id: str) -> str:
    digest = hashlib.sha256(f"{tenant_id}\x1f{kind}\x1f{record_id}".encode()).hexdigest()
    return "vt-" + digest[:40]


def entity_digest(entity: Mapping[str, Any]) -> str:
    canonical = json.dumps(entity, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


# ---------------------------------------------------------------- input validation


def _fail(message: str, field: str, reason: str) -> MappingError:
    return MappingError(message, field=field, reason=reason)


def _opt_str(record: Mapping[str, Any], key: str, where: str) -> str | None:
    if record.get(key) is None:
        return None
    return _str(record, key, where)


def _str(record: Mapping[str, Any], key: str, where: str) -> str:
    value = record.get(key)
    if not isinstance(value, str) or not value.strip() or len(value) > 500:
        raise _fail(f"{where}.{key} must be a non-empty string", f"{where}.{key}", "invalid")
    return value.strip()


def _record_id(record: Mapping[str, Any], key: str, where: str) -> str:
    value = _str(record, key, where)
    if not RECORD_ID.fullmatch(value):
        raise _fail(f"{where}.{key} is not a valid record ID", f"{where}.{key}", "invalid")
    return value


def _date(record: Mapping[str, Any], key: str, where: str) -> str | None:
    value = record.get(key)
    if value is None:
        return None
    try:
        if not isinstance(value, str) or not DATE.fullmatch(value):
            raise ValueError
        date.fromisoformat(value)
    except ValueError:
        raise _fail(f"{where}.{key} must be YYYY-MM-DD", f"{where}.{key}", "invalid_date")
    return value


def _money(record: Mapping[str, Any], key: str, where: str) -> str:
    value = record.get(key)
    if not isinstance(value, str) or not MONEY.fullmatch(value):
        raise _fail(
            f"{where}.{key} must be a decimal string with two places",
            f"{where}.{key}",
            "invalid_amount",
        )
    return value


def _currency(record: Mapping[str, Any], where: str) -> str:
    value = record.get("currency")
    if not isinstance(value, str) or not CURRENCY.fullmatch(value):
        raise _fail(f"{where}.currency must be ISO 4217", f"{where}.currency", "invalid")
    return value


def _source(record: Mapping[str, Any], where: str) -> dict[str, str]:
    source = record.get("source")
    if not isinstance(source, Mapping):
        raise _fail(f"{where}.source is required", f"{where}.source", "missing_provenance")
    system = source.get("system")
    if system not in SOURCE_SYSTEMS:
        raise _fail(
            f"{where}.source.system must be one of {sorted(SOURCE_SYSTEMS)}",
            f"{where}.source.system",
            "invalid",
        )
    return {
        "system": system,
        "record_type": _record_id(source, "record_type", f"{where}.source"),
        "record_id": _record_id(source, "record_id", f"{where}.source"),
    }


def _citations(
    record: Mapping[str, Any], where: str, evidence: Mapping[str, str]
) -> list[dict[str, Any]]:
    """Validate contract ``EvidenceRef`` values against the bundle's evidence list."""
    refs = record.get("evidence", [])
    if not isinstance(refs, list):
        raise _fail(f"{where}.evidence must be a list", f"{where}.evidence", "invalid")
    out: list[dict[str, Any]] = []
    for i, ref in enumerate(refs):
        at = f"{where}.evidence[{i}]"
        if not isinstance(ref, Mapping) or set(ref) != {
            "evidence_id",
            "document_sha256",
            "locator",
        }:
            raise _fail(f"{at} must be an EvidenceRef", at, "invalid")
        known = evidence.get(ref["evidence_id"])
        if known is None:
            raise _fail(f"{at} cites evidence that is not in the bundle", at, "unknown_evidence")
        if ref["document_sha256"] != known:
            raise _fail(
                f"{at} cites a document hash that differs from the stored original",
                f"{at}.document_sha256",
                "provenance_hash_mismatch",
            )
        locator = ref["locator"]
        if not isinstance(locator, Mapping) or set(locator) != {"page", "record"}:
            raise _fail(f"{at}.locator must have page and record", f"{at}.locator", "invalid")
        page, rec = locator["page"], locator["record"]
        if page is not None and (not isinstance(page, int) or isinstance(page, bool) or page < 1):
            raise _fail(f"{at}.locator.page must be >= 1", f"{at}.locator.page", "invalid")
        if rec is not None and (not isinstance(rec, str) or not 1 <= len(rec) <= 255):
            raise _fail(f"{at}.locator.record is invalid", f"{at}.locator.record", "invalid")
        if page is None and rec is None:
            raise _fail(f"{at} needs a page or record locator", f"{at}.locator", "missing_locator")
        out.append(
            {
                "evidence_id": ref["evidence_id"],
                "document_sha256": ref["document_sha256"],
                "locator": {"page": page, "record": rec},
            }
        )
    return out


def _unique(items: Iterable[Mapping[str, Any]], key: str, where: str) -> None:
    seen: set[str] = set()
    for i, item in enumerate(items):
        value = str(item.get(key))
        if value in seen:
            raise _fail(f"{where}[{i}].{key} repeats {value}", f"{where}[{i}].{key}", "duplicate")
        seen.add(value)


def _list(bundle: Mapping[str, Any], key: str) -> list[Mapping[str, Any]]:
    value = bundle.get(key, [])
    if not isinstance(value, list) or not all(isinstance(x, Mapping) for x in value):
        raise _fail(f"{key} must be a list of objects", key, "invalid")
    _unique(value, "evidence_id" if key == "evidence" else "id", key)
    return value


# ---------------------------------------------------------------- mapping


class _Mapper:
    def __init__(self, tenant_id: str) -> None:
        self.tenant_id = tenant_id
        self.entities: list[dict[str, Any]] = []
        self.extensions: list[dict[str, Any]] = []
        self.evidence: dict[str, str] = {}  # evidence_id -> sha256
        self.proofs: dict[str, str] = {}  # evidence_id -> Document entity id
        self.parties: dict[str, tuple[str, str]] = {}  # record id -> (entity id, schema)
        self.contracts: dict[str, str] = {}
        self.invoices: dict[str, tuple[str, str | None]] = {}  # id -> (entity id, contract)
        self.stakes: list[dict[str, Any]] = []

    def add(
        self,
        kind: str,
        record_id: str,
        schema: str,
        props: Mapping[str, Any],
        source: dict[str, str],
        citations: list[dict[str, Any]],
        tax: dict[str, Any],
    ) -> str:
        eid = entity_id(self.tenant_id, kind, record_id)
        properties: dict[str, list[str]] = {}
        for key, vals in props.items():
            values = sorted(
                {str(v) for v in (vals if isinstance(vals, list) else [vals]) if v is not None}
            )
            if values:
                properties[key] = values
        self.entities.append({"id": eid, "schema": schema, "properties": properties})
        self.extensions.append(
            {
                "version": EXTENSION_VERSION,
                "entity_id": eid,
                "schema": schema,
                "kind": kind,
                "tenant_id": self.tenant_id,
                "source": source,
                "evidence": citations,
                "tax": tax,
                "conflict_ids": [],
            }
        )
        return eid

    def proof_ids(self, citations: list[dict[str, Any]]) -> list[str]:
        return [self.proofs[c["evidence_id"]] for c in citations]

    def party(self, record: Mapping[str, Any], key: str, where: str, *, asset: bool = False) -> str:
        ref = _record_id(record, key, where)
        if ref not in self.parties:
            raise _fail(
                f"{where}.{key} refers to an unknown party", f"{where}.{key}", "unknown_party"
            )
        eid, schema = self.parties[ref]
        if asset and "Asset" not in SUBSET["schemata"][schema]["is_a"]:
            raise _fail(
                f"{where}.{key} must be a company: FtM Ownership.asset has range Asset",
                f"{where}.{key}",
                "invalid_ownership_asset",
            )
        return eid

    def map_evidence(self, ev: Mapping[str, Any], where: str) -> None:
        ev_id = _str(ev, "evidence_id", where)
        try:
            uuid.UUID(ev_id)
        except ValueError:
            raise _fail(f"{where}.evidence_id must be a UUID", f"{where}.evidence_id", "invalid")
        sha = ev.get("document_sha256")
        if not isinstance(sha, str) or not SHA256.fullmatch(sha):
            raise _fail(
                f"{where}.document_sha256 must be lowercase hex SHA-256",
                f"{where}.document_sha256",
                "invalid",
            )
        media = ev.get("media_type")
        if media not in MEDIA_TYPES:
            raise _fail(f"{where}.media_type is not allowed", f"{where}.media_type", "invalid")
        size = ev.get("size")
        if (
            not isinstance(size, int)
            or isinstance(size, bool)
            or not 1 <= size <= MAX_EVIDENCE_BYTES
        ):
            raise _fail(f"{where}.size must be 1..{MAX_EVIDENCE_BYTES}", f"{where}.size", "invalid")
        file_name = _str(ev, "file_name", where)
        self.evidence[ev_id] = sha
        self.proofs[ev_id] = self.add(
            "evidence",
            ev_id,
            "Document",
            {
                "fileName": file_name,
                "title": _opt_str(ev, "title", where) or file_name,
                "mimeType": media,
                "fileSize": size,
                "date": _date(ev, "received_on", where),
            },
            {"system": "frappe", "record_type": "Vati Evidence", "record_id": ev_id},
            [],
            {"document_sha256": sha},
        )

    def map_party(self, p: Mapping[str, Any], where: str) -> None:
        pid = _record_id(p, "id", where)
        kind = p.get("kind")
        if kind not in PARTY_SCHEMA:
            raise _fail(
                f"{where}.kind must be one of {sorted(PARTY_SCHEMA)}", f"{where}.kind", "invalid"
            )
        country = p.get("country")
        if country is not None and (not isinstance(country, str) or not COUNTRY.fullmatch(country)):
            raise _fail(
                f"{where}.country must be ISO 3166-1 alpha-2, lower case",
                f"{where}.country",
                "invalid",
            )
        role = p.get("role", "counterparty")
        if role not in PARTY_ROLES:
            raise _fail(
                f"{where}.role must be one of {sorted(PARTY_ROLES)}", f"{where}.role", "invalid"
            )
        props: dict[str, Any] = {
            "name": _str(p, "name", where),
            "taxNumber": _opt_str(p, "tax_number", where),
            "idNumber": _opt_str(p, "id_number", where),
            "country": country,
        }
        if kind == "person":
            if p.get("registration_number") is not None:
                raise _fail(
                    "A person has no registration number", f"{where}.registration_number", "invalid"
                )
            props.update(
                firstName=_opt_str(p, "first_name", where),
                lastName=_opt_str(p, "last_name", where),
                birthDate=_date(p, "birth_date", where),
            )
        else:
            props["registrationNumber"] = _opt_str(p, "registration_number", where)
            if kind == "company":
                props["incorporationDate"] = _date(p, "incorporation_date", where)
        citations = _citations(p, where, self.evidence)
        schema = PARTY_SCHEMA[kind]
        eid = self.add("party", pid, schema, props, _source(p, where), citations, {"role": role})
        self.parties[pid] = (eid, schema)

    def map_contract(self, c: Mapping[str, Any], where: str) -> None:
        cid = _record_id(c, "id", where)
        related = c.get("related_party")
        if not isinstance(related, bool):
            raise _fail(
                f"{where}.related_party must be true or false", f"{where}.related_party", "invalid"
            )
        title = _str(c, "title", where)
        buyer = self.party(c, "buyer_id", where)
        supplier = self.party(c, "supplier_id", where)
        source = _source(c, where)
        citations = _citations(c, where, self.evidence)
        proofs = self.proof_ids(citations)
        tax = {"related_party": related}
        self.contracts[cid] = self.add(
            "contract",
            cid,
            "Contract",
            {
                "title": title,
                "name": title,
                "authority": buyer,
                "contractDate": _date(c, "date", where),
                "proof": proofs,
            },
            source,
            citations,
            tax,
        )
        self.add(
            "contract_award",
            cid,
            "ContractAward",
            {
                "contract": self.contracts[cid],
                "supplier": supplier,
                "recordId": cid,
                "role": "Supplier",
                "proof": proofs,
            },
            source,
            citations,
            dict(tax),
        )

    def map_invoice(self, inv: Mapping[str, Any], where: str) -> None:
        iid = _record_id(inv, "id", where)
        direction = inv.get("direction")
        if direction not in INVOICE_ROLE:
            raise _fail(
                f"{where}.direction must be purchase or sale", f"{where}.direction", "invalid"
            )
        contract_ref = inv.get("contract_id")
        if contract_ref is not None and contract_ref not in self.contracts:
            raise _fail(
                f"{where}.contract_id is unknown", f"{where}.contract_id", "unknown_contract"
            )
        supplier = self.party(inv, "supplier_id", where)
        buyer = self.party(inv, "buyer_id", where)
        citations = _citations(inv, where, self.evidence)
        tax = {
            "direction": direction,
            "currency": _currency(inv, where),
            "net_amount": _money(inv, "net_amount", where),
            "vat_amount": _money(inv, "vat_amount", where),
            "gross_amount": _money(inv, "gross_amount", where),
            "contract_record_id": contract_ref,
        }
        role = INVOICE_ROLE[direction]
        eid = self.add(
            "invoice",
            iid,
            "UnknownLink",
            {
                "subject": supplier,
                "object": buyer,
                "role": role,
                "date": _date(inv, "issue_date", where),
                "recordId": iid,
                "proof": self.proof_ids(citations),
                "description": (
                    f"{role} {iid}: net {tax['net_amount']}, VAT {tax['vat_amount']}, "
                    f"gross {tax['gross_amount']} {tax['currency']}"
                ),
            },
            _source(inv, where),
            citations,
            tax,
        )
        self.invoices[iid] = (eid, contract_ref)

    def map_payment(self, pay: Mapping[str, Any], where: str) -> None:
        pay_id = _record_id(pay, "id", where)
        invoice_ref = pay.get("invoice_id")
        if invoice_ref is not None and invoice_ref not in self.invoices:
            raise _fail(f"{where}.invoice_id is unknown", f"{where}.invoice_id", "unknown_invoice")
        invoice_eid, contract_ref = self.invoices[invoice_ref] if invoice_ref else (None, None)
        payer = self.party(pay, "payer_id", where)
        beneficiary = self.party(pay, "beneficiary_id", where)
        amount = _money(pay, "amount", where)
        currency = _currency(pay, where)
        citations = _citations(pay, where, self.evidence)
        self.add(
            "payment",
            pay_id,
            "Payment",
            {
                "payer": payer,
                "beneficiary": beneficiary,
                "amount": amount,
                "currency": currency,
                "date": _date(pay, "date", where),
                "recordId": pay_id,
                "purpose": f"Settlement of invoice {invoice_ref}" if invoice_ref else None,
                "contract": self.contracts[contract_ref] if contract_ref else None,
                "proof": self.proof_ids(citations),
            },
            _source(pay, where),
            citations,
            {
                "amount": amount,
                "currency": currency,
                "invoice_record_id": invoice_ref,
                "invoice_entity_id": invoice_eid,
            },
        )

    def map_ownership(self, o: Mapping[str, Any], where: str) -> None:
        oid = _record_id(o, "id", where)
        owner = self.party(o, "owner_id", where)
        asset = self.party(o, "asset_id", where, asset=True)
        if owner == asset:
            raise _fail(
                f"{where} says an entity owns itself", f"{where}.owner_id", "self_ownership"
            )
        raw_pct = o.get("percentage")
        try:
            if not isinstance(raw_pct, str) or not PERCENT.fullmatch(raw_pct):
                raise InvalidOperation
            pct = Decimal(raw_pct)
            if not Decimal(0) < pct <= HUNDRED:
                raise InvalidOperation
        except InvalidOperation:
            raise _fail(
                f"{where}.percentage must be a decimal string in (0, 100]",
                f"{where}.percentage",
                "invalid",
            )
        kind = o.get("ownership_type")
        if kind is not None and kind not in OWNERSHIP_TYPES:
            raise _fail(
                f"{where}.ownership_type must be one of {sorted(OWNERSHIP_TYPES)}",
                f"{where}.ownership_type",
                "invalid",
            )
        start, end = _date(o, "start_date", where), _date(o, "end_date", where)
        if start and end and end < start:
            raise _fail(
                f"{where}.end_date is before start_date", f"{where}.end_date", "invalid_date"
            )
        citations = _citations(o, where, self.evidence)
        eid = self.add(
            "ownership",
            oid,
            "Ownership",
            {
                "owner": owner,
                "asset": asset,
                "percentage": raw_pct,
                "ownershipType": kind,
                "startDate": start,
                "endDate": end,
                "recordId": oid,
                "proof": self.proof_ids(citations),
            },
            _source(o, where),
            citations,
            {"percentage": raw_pct},
        )
        self.stakes.append(
            {
                "record_id": oid,
                "entity_id": eid,
                "owner": owner,
                "asset": asset,
                "pct": pct,
                "type": kind,
                "start": start,
                "end": end,
            }
        )


def map_bundle(bundle: Mapping[str, Any]) -> MappingResult:
    """Validate a ``tax_entity_bundle.v1`` and map it to FtM entities plus extensions."""
    if bundle.get("version") != BUNDLE_VERSION:
        raise _fail(f"version must be {BUNDLE_VERSION}", "version", "unsupported_version")
    tenant_id = bundle.get("tenant_id")
    try:
        if not isinstance(tenant_id, str) or uuid.UUID(tenant_id).version != 4:
            raise ValueError
    except ValueError:
        raise _fail("tenant_id must be a UUIDv4", "tenant_id", "invalid")
    m = _Mapper(tenant_id)
    # Order matters: later kinds refer to earlier ones.
    for i, ev in enumerate(_list(bundle, "evidence")):
        m.map_evidence(ev, f"evidence[{i}]")
    for i, p in enumerate(_list(bundle, "parties")):
        m.map_party(p, f"parties[{i}]")
    for i, c in enumerate(_list(bundle, "contracts")):
        m.map_contract(c, f"contracts[{i}]")
    for i, inv in enumerate(_list(bundle, "invoices")):
        m.map_invoice(inv, f"invoices[{i}]")
    for i, pay in enumerate(_list(bundle, "payments")):
        m.map_payment(pay, f"payments[{i}]")
    for i, o in enumerate(_list(bundle, "ownership")):
        m.map_ownership(o, f"ownership[{i}]")

    conflicts = ownership_conflicts(m.stakes)
    by_entity = {x["entity_id"]: x for x in m.extensions}
    for conflict in conflicts:
        for eid in conflict["entity_ids"]:
            by_entity[eid]["conflict_ids"].append(conflict["id"])
    entities = sorted(m.entities, key=lambda e: e["id"])
    validate_entities(entities)
    return MappingResult(
        entities=entities,
        extensions=sorted(m.extensions, key=lambda x: x["entity_id"]),
        conflicts=conflicts,
        digests={e["id"]: entity_digest(e) for e in entities},
    )


# ---------------------------------------------------------------- ownership conflicts


def _overlaps(a: Mapping[str, Any], b: Mapping[str, Any]) -> bool:
    a_start, a_end = a["start"] or OPEN_START, a["end"] or OPEN_END
    b_start, b_end = b["start"] or OPEN_START, b["end"] or OPEN_END
    return bool(a_start <= b_end and b_start <= a_end)


def ownership_conflicts(stakes: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Flag ownership records that cannot all be true. Nothing is resolved.

    - ``disagreeing_ownership_records``: the same owner, asset and ownership type with
      overlapping periods but different percentages.
    - ``ownership_exceeds_100_percent``: at some date the direct stakes recorded for one
      asset add up to more than 100%. Only ``direct`` (or untyped) stakes are summed,
      because beneficial and indirect stakes legitimately overlap them.
    """
    found: dict[str, dict[str, Any]] = {}

    def add(reason: str, records: list[dict[str, Any]], **detail: Any) -> None:
        ids = sorted(r["record_id"] for r in records)
        key = hashlib.sha256(f"{reason}\x1f{','.join(ids)}".encode()).hexdigest()[:16]
        found.setdefault(
            key,
            {
                "id": "own-conflict-" + key,
                "reason": reason,
                "asset_entity_id": records[0]["asset"],
                "record_ids": ids,
                "entity_ids": sorted(r["entity_id"] for r in records),
                **detail,
            },
        )

    for i, a in enumerate(stakes):
        for b in stakes[i + 1 :]:
            same_stake = (a["owner"], a["asset"], a["type"]) == (b["owner"], b["asset"], b["type"])
            if same_stake and a["pct"] != b["pct"] and _overlaps(a, b):
                add(
                    "disagreeing_ownership_records",
                    [a, b],
                    percentages=sorted({str(a["pct"]), str(b["pct"])}),
                )

    direct = [s for s in stakes if s["type"] in (None, "direct")]
    for asset in sorted({s["asset"] for s in direct}):
        held = [s for s in direct if s["asset"] == asset]
        # The total only rises where a stake starts, so checking each start date is enough.
        for point in sorted({s["start"] or OPEN_START for s in held}):
            active = [s for s in held if _overlaps(s, {"start": point, "end": point})]
            total = sum((s["pct"] for s in active), Decimal(0))
            if total > HUNDRED:
                add(
                    "ownership_exceeds_100_percent",
                    active,
                    on_date=None if point == OPEN_START else point,
                    total_percentage=str(total),
                )
    return sorted(found.values(), key=lambda c: c["id"])


# ---------------------------------------------------------------- FtM conformance


def validate_entities(entities: list[dict[str, Any]], subset: Mapping[str, Any] = SUBSET) -> None:
    """Check entities against the locked FtM schema subset: known non-abstract schema,
    known properties, value types, required properties and entity-reference ranges."""
    schemata = subset["schemata"]
    by_id = {e["id"]: e for e in entities}
    if len(by_id) != len(entities):
        raise EntityValidationError("Duplicate entity IDs")
    for e in entities:
        spec = schemata.get(e.get("schema"))
        if spec is None or spec["abstract"]:
            raise EntityValidationError(f"{e.get('id')}: schema {e.get('schema')} is not allowed")
        if set(e) != {"id", "schema", "properties"}:
            raise EntityValidationError(f"{e['id']}: unexpected keys {sorted(e)}")
        props = e["properties"]
        for name in spec["required"]:
            if not props.get(name):
                raise EntityValidationError(f"{e['id']}: required property {name} missing")
        for name, values in props.items():
            prop = spec["properties"].get(name)
            if prop is None:
                raise EntityValidationError(f"{e['id']}: {e['schema']} has no property {name}")
            if not isinstance(values, list) or not values:
                raise EntityValidationError(f"{e['id']}.{name}: values must be a non-empty list")
            for value in values:
                _check_value(f"{e['id']}.{name}", prop, value, by_id, schemata)


def _check_value(
    where: str,
    prop: Mapping[str, Any],
    value: Any,
    by_id: Mapping[str, Mapping[str, Any]],
    schemata: Mapping[str, Any],
) -> None:
    if not isinstance(value, str) or not value or len(value) > 65_000:
        raise EntityValidationError(f"{where}: values must be non-empty strings")
    kind = prop["type"]
    if kind == "entity":
        target = by_id.get(value)
        if target is None:
            raise EntityValidationError(f"{where}: dangling reference {value}")
        if prop["range"] not in schemata[target["schema"]]["is_a"]:
            raise EntityValidationError(f"{where}: {target['schema']} is not a {prop['range']}")
    elif kind == "date" and not FTM_DATE.fullmatch(value):
        raise EntityValidationError(f"{where}: invalid date {value}")
    elif kind == "number" and not FTM_NUMBER.fullmatch(value):
        raise EntityValidationError(f"{where}: invalid number {value}")
    elif kind == "country" and not COUNTRY.fullmatch(value):
        raise EntityValidationError(f"{where}: invalid country {value}")
    elif kind == "mimetype" and value not in MEDIA_TYPES:
        raise EntityValidationError(f"{where}: unexpected media type {value}")


